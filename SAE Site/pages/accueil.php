<section class="presentation-ami">
    <h2>Présentation de l'A.M.i</h2>
    <div class="presentation">
        <div class="ami">
            <h3>Qu’est-ce que l’A.M.i ?</h3>
            <p>
                L’A.M.i (Association nationale de défense des Malades, Invalides et handicapés), est une association loi 1901 présente sur le territoire français au travers de comités locaux et départementaux.
                Née en 1936 dans les sanatoriums au cœur des combats des travailleurs atteints de tuberculose au sein de la FNTC puis de la FNLA, l’A.M.i regroupe depuis 1964 des personnes handicapées ou malades, des parents d’enfants handicapés et des personnes valides qui ont choisi de lutter pour que les personnes handicapées puissent :
                Vivre, étudier, travailler, se cultiver avec l’ensemble des citoyennes et citoyens.
                L’A.M.i refuse la pitié et l’assistance : elle est l'une des rares associations à ne gérer aucun établissement ou service, garantissant ainsi une indépendance totale vis-à-vis des structures d’accueil et de travail.
            </p>
        </diV>
        <div class="objectif">
            <h3>Objectifs de l’A.M.i</h3>
            <p>
                L’association consacre tous ses moyens à :
            </p>
            <ul>
                <li>Rompre l’isolement, le silence et la misère.</li>
                <li>Permettre aux citoyens handicapés ou malades de s’intégrer pleinement dans tous les aspects de la vie scolaire, professionnelle, sociale et culturelle.</li>
                <li>Revendiquer des ressources décentes et la compensation de tous les surcoûts liés au handicap.</li>
                <li>Faire respecter la dignité des personnes malades (notamment lors des hospitalisations) et des personnes handicapées en établissement.</li>
                <li>Informer sur leurs droits pour encourager la responsabilité et refuser l’assistanat.</li>
                <li>Défendre et promouvoir un système de protection sociale garantissant le droit à la santé sans reste à charge pour les soins et médicaments.</li>
                <li>Réfléchir aux causes des difficultés rencontrées et trouver des moyens d’agir collectivement.</li>
            </ul>
        </div>
        <div class="Mission">
            <h3>Nos Missions</h3>
            <p> Nos missions sont les suivantes : </p>
            <ul>
                <li>
                    Aider les personnes en situation de handicap en faisant valoir leurs droits face à l’administration.
                </li>
                <li>
                    Sensibiliser le public aux difficultés et besoins des personnes en situation de handicap.
                </li>
                <li>
                    Interpeller les pouvoirs publics en leur proposant des évolutions, des réglementations et des lois.
                </li>
                <li>
                    Recevoir et guider toute personne en difficulté, perdue dans les méandres administratifs, et l’assister en cas de litige.
                </li>
                <li>
                    Former à l’utilisation des outils numériques pour favoriser l’inclusion.
                </li>
            </ul>
        </div>
        <div class="lutte">
            <h3>L’A.M.i lutte pour :</h3>
            <ul>
                <li>Des ressources décentes avec une AAH égale à 100 % du SMIC net.</li>
                <li>Une véritable compensation de tous les surcoûts dus au handicap.</li>
                <li>Un statut de salarié à part entière pour les travailleurs handicapés en ESAT.</li>
                <li>La dénonciation des maltraitances dans de nombreux établissements pour personnes handicapées ou âgées.</li>
            </ul>
        </div>
    </div>
</section>
